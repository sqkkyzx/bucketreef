function translateDynamicMessage(message: string): string | null {
  let match = /^Duplicate tag key: (.+)$/.exec(message);
  if (match) return `标签键重复：${match[1]}`;
  match = /^Rule (\d+): Destination bucket ARN is required\.$/.exec(message);
  if (match) return `规则 ${match[1]}：必须填写目标存储桶 ARN。`;
  match = /^Rule (\d+): Priority must be a positive integer\.$/.exec(message);
  if (match) return `规则 ${match[1]}：优先级必须是正整数。`;
  match = /^Prefix: (.+)$/.exec(message);
  if (match) return `前缀：${match[1]}`;
  match = /^Tag: (.+)$/.exec(message);
  if (match) return `标签：${match[1]}`;
  match = /^Tags: (.+)$/.exec(message);
  if (match) return `标签：${match[1]}`;
  match = /^Expire current objects after (\d+)d$/.exec(message);
  if (match) return `${match[1]} 天后使当前对象过期`;
  match = /^Expire noncurrent versions after (\d+)d$/.exec(message);
  if (match) return `${match[1]} 天后使非当前版本过期`;
  match = /^Abort incomplete multipart uploads after (\d+)d$/.exec(message);
  if (match) return `${match[1]} 天后中止未完成的分段上传`;
  match = /^Transitions \((\d+)\)$/.exec(message);
  if (match) return `转换（${match[1]}）`;
  match = /^Noncurrent transitions \((\d+)\)$/.exec(message);
  if (match) return `非当前版本转换（${match[1]}）`;
  return null;
}

export function useManagerBucketDetailText() {
  const { locale } = useI18n();
  const t = useCallback(
    (message: string | I18nMessage | null | undefined) => {
      if (message == null) return "";
      if (typeof message !== "string") {
        return message[locale] ?? message.en ?? message.fr ?? message.de ?? message.zh ?? "";
      }
      if (locale !== "zh") return message;
      return managerBucketDetailZhMessages[message] ?? translateDynamicMessage(message) ?? message;
    },
    [locale],
  );
  return { locale, t };
}
