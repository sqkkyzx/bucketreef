export function useAdminOperationsText() {
  const { locale } = useI18n();
  const t = useCallback(
    (message: string | I18nMessage) => {
      if (typeof message !== "string") {
        return message[locale] ?? message.en ?? message.fr ?? message.de ?? message.zh ?? "";
      }
      return locale === "zh" ? zhMessages[message] ?? message : message;
    },
    [locale],
  );
  return { locale, t };
}

export function localizeAdminOperationsBreadcrumbs(
  breadcrumbs: PageBreadcrumb[],
  locale: AdminOperationsLocale,
): PageBreadcrumb[] {
  if (locale !== "zh") return breadcrumbs;
  return breadcrumbs.map((breadcrumb) => ({
    ...breadcrumb,
    label: breadcrumb.label === "Admin" ? "管理后台" : zhMessages[breadcrumb.label] ?? breadcrumb.label,
  }));
}
