export type AdminPrincipalText = (
  message: string | I18nMessage,
  values?: Record<string, string | number>,
) => string;

export function useAdminPrincipalText() {
  const { locale } = useI18n();
  const t: AdminPrincipalText = useCallback(
    (message, values) => {
      const source = typeof message === "string"
        ? (locale === "zh" ? zhMessages[message] ?? message : message)
        : message[locale] ?? message.en ?? message.fr ?? message.de ?? message.zh ?? "";
      return source.replace(/\{(\w+)\}/g, (match, name: string) =>
        String(values?.[name] ?? match),
      );
    },
    [locale],
  );
  return { locale, t };
}

export function localizedAdminPrincipalBreadcrumbs(
  pageId: "users" | "groups",
  locale: "en" | "fr" | "de" | "zh",
  ...trailingBreadcrumbs: PageBreadcrumb[]
): PageBreadcrumb[] {
  const crumbs = adminPageBreadcrumbs(pageId, ...trailingBreadcrumbs);
  if (locale !== "zh") return crumbs;
  return crumbs.map((crumb, index) => ({
    ...crumb,
    label: index === 0
      ? "管理后台"
      : index === 1
        ? pageId === "users" ? "界面用户" : "界面用户组"
        : crumb.label,
  }));
}
